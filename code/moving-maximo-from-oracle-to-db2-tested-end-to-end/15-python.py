"""Write a DB2 script that puts IBM's DB2 wording back on IBM's own records after an Oracle-to-DB2 move.

Created by Mohamed Chihaoui.

Input : ibm_platform_diff.csv from diff_ibm_platform_rows.py (same Maximo version and add-ons
        as the converted database: the maxdemo files must come from the same build).
Output: ibm_db2_text_fix.sql, one guarded UPDATE per record. The guard (column = IBM's Oracle
        text) means a record the customer has changed is left alone and shows up in the
        finder report instead.

Usage: python ibm_db2_text_fix.py ibm_platform_diff.csv ibm_db2_text_fix.sql
"""
import csv
import re
import sys

# table -> (SQL-bearing columns, natural key columns in the order the diff wrote them)
TABLES = {
    "MAXRELATIONSHIP": (("WHERECLAUSE",), ("PARENT", "NAME")),
    "QUERY": (("CLAUSE",), ("APP", "CLAUSENAME", "OWNER")),
    "OSLCQUERY": (("CLAUSE",), ("INTOBJECTNAME", "CLAUSENAME")),
    "KPIMAIN": (("CLAUSE", "SELECTSTMT"), ("KPINAME",)),
    "CONDITION": (("EXPRESSION",), ("CONDITIONNUM",)),
    "ESCALATION": (("CONDITION",), ("ESCALATION",)),
    "MAXINTOBJECT": (("RESTRICTWHERE",), ("INTOBJECTNAME",)),
    "MAXTABLEDOMAIN": (("VALIDTNWHERECLAUSE", "LISTWHERECLAUSE"), ("DOMAINID", "OBJECTNAME", "ORGID", "SITEID")),
    "MAXPROP": (("MAXIMODEFAULT",), ("PROPNAME",)),
    "MAXPROPVALUE": (("PROPVALUE",), ("PROPNAME", "SERVERNAME", "SERVERHOST")),
}
WS = re.compile(r"\s+")

def lit(v):
    return "'" + v.replace("'", "''") + "'"

def main(src, out):
    n = 0
    lines = ["-- Generated by ibm_db2_text_fix.py (Created by Mohamed Chihaoui)",
             "-- Run on the converted DB2 database:  db2 -tvf ibm_db2_text_fix.sql", ""]
    for r in csv.DictReader(open(src, encoding="utf-8")):
        spec = TABLES.get(r["table"])
        if not spec or r["column"] not in spec[0]:
            continue
        if WS.sub(" ", r["oracle_text"]).strip().lower() == WS.sub(" ", r["db2_text"]).strip().lower():
            continue   # only spacing differs
        keys = r["key"].split("|")
        cond = []
        for c, v in zip(spec[1], keys):
            cond.append(f"{c} is null" if v == "None" else f"{c} = {lit(v)}")
        cond.append(f"{r['column']} = {lit(r['oracle_text'])}")
        lines.append(f"-- {r['table']} {r['key']}")
        lines.append(f"update {r['table'].lower()} set {r['column'].lower()} = {lit(r['db2_text'])}\n  where "
                     + "\n    and ".join(cond) + ";")
        n += 1
    lines += ["", "commit;"]
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print(n, "guarded updates ->", out)

if __name__ == "__main__":
    main(*sys.argv[1:3])
