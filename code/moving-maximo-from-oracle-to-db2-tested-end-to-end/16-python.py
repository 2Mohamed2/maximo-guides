"""Turn db2_rewrites.csv (rewrites proven by dual_run.py) into UPDATE statements for the DB2 database.

Created by Mohamed Chihaoui.

Usage: python rewrites_to_sql.py db2_rewrites.csv db2_rewrites.sql
       db2 -tvf db2_rewrites.sql      (connected to the converted database, schema set to the Maximo owner)
"""
import csv
import sys

def lit(v):
    return "'" + v.replace("'", "''") + "'"

def main(src, out):
    rows = list(csv.DictReader(open(src, encoding="utf-8")))
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- Generated by rewrites_to_sql.py (Created by Mohamed Chihaoui)\n")
        for r in rows:
            f.write(f"-- {r['app']} / {r['clausename']}: {r['why']}\n")
            f.write(f"update query set clause = {lit(r['db2_clause'])}\n"
                    f"  where app = {lit(r['app'])} and clausename = {lit(r['clausename'])} and owner = {lit(r['owner'])};\n")
        f.write("commit;\n")
    print(len(rows), "updates ->", out)

if __name__ == "__main__":
    main(*sys.argv[1:3])
